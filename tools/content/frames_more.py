MAIN_ENDINGS = ["기본", "생사경", "배드", "사망"]

def apply(N):
    def add(key, rows):
        if key not in N["frames"]: return
        texts = {t for _, t in rows}
        N["frames"][key] = [g for g in N["frames"][key] if not (isinstance(g, dict) and any(r["text"] in texts for r in g.get("rows", [])))]
        N["frames"][key].append({"many": 2, "rows": [{"requires": {"flag": f}, "text": t} for f, t in rows]})
    for origin, rows in SIDE.items():
        for key, o in N["side"].items():
            if o == origin: add(key, rows)
    for key in MAIN_ENDINGS: add(key, MAIN)
