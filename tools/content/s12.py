def cb_event(key, origin, chapters, title, text, choices): rnd(key, chapters, title, text, choices, origin=origin, req=dict(CB))
def cb_choice(event, choice):
    ev=RANDOM.get(event) or STORY[event]
    choice["requires"]=dict(CB, **choice.get("requires",{})); choice["hidden"]=True
    ev["choices"].append(choice)
def cb_line(ending, text):
    "결말마다 천붕의 한 줄. 깊은 강호의 줄 묶음이 있으면 맨 앞에 둔다"
    group=None
    for g in ENDINGS[ending]["frames"]:
        if isinstance(g,list) and g and all("difficulty_min" in r.get("requires",{}) and len(r["requires"])==1 for r in g): group=g; break
    row={"requires":dict(CB),"text":text}
    if group is None: ENDINGS[ending]["frames"].append([row])
    else: group.insert(0,row)
def rows_cb(origin, *items):
    group={"rows":[{"requires":dict(CB, **r),"text":t} for r,t in items],"many":1}
    for key,d in ENDINGS.items():
        if d["origin"]==origin: d["frames"].append(group)
