from dsl import *

def atk(name, cat, origin, desc, forms, secret, g, text, mult=2.2, qi=16, s_mult=3.0, s_qi=80):
    g = dict(g); g["text"] = text
    return {"name": name, "category": cat, "type": "공격무공", "grade": "신공", "base_multiplier": mult, "qi_cost": qi, "desc": desc,
            "forms": forms, "secret_technique": {"name": secret, "unlock_grade": "신공", "unlock_mastery": 40, "multiplier": s_mult, "qi_cost": s_qi},
            "origin": origin, "gimmick": g}
def mind(name, origin, desc, effect, g, text, grade="신공"):
    g = dict(g); g["text"] = text
    return {"name": name, "type": "심공", "category": "심공", "grade": grade, "base_multiplier": 1, "qi_cost": 0, "desc": desc,
            "effect": effect, "origin": origin, "gimmick": g}
def move(name, origin, desc, effect, g, text, qi=10, grade="신공"):
    g = dict(g); g["text"] = text
    return {"name": name, "type": "경공", "category": "경공", "grade": grade, "base_multiplier": 1, "qi_cost": qi, "desc": desc,
            "effect": effect, "origin": origin, "gimmick": g}
def E(hp, qi, atk_, rounds): return {"heal_hp_pct": hp, "heal_qi_pct": qi, "atk_buff_pct": atk_, "buff_rounds": rounds}
def M(ev, co, fl): return {"evade": ev, "counter_pct": co, "flee_bonus": fl}

