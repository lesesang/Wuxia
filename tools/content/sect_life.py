import json, os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
D = os.path.join(ROOT, "www", "data")
def load(n): return json.load(open(os.path.join(D, n + ".json"), encoding="utf-8"))
def save(n, d):
    with open(os.path.join(D, n + ".json"), "w", encoding="utf-8") as f: f.write(json.dumps(d, ensure_ascii=False, indent=2) + "\n")

def C(label, text, eff=None, req=None, hidden=False, tag=None):
    c = {"label": label, "outcomes": [{"text": text, "effects": eff or {}}]}
    if req: c["requires"] = req
    if hidden: c["hidden"] = True
    if tag: c["tag"] = tag
    return c
def R(req, text): return {"requires": req, "text": text}
def B(battle, foe, line, **eff): return {"battle": battle, "foe": foe, "foe_line": line, **eff}
MA = lambda n: {"마도": n}
SA = lambda n: {"사도": n}
JA = lambda n: {"정도": n}

EV = {}
def E(key, sect, ch, title, text, choices, reacts=None, variants=None, req=None):
    r = {"sect": sect}
    if req: r.update(req)
    e = {"chapters": ch, "requires": r, "title": title, "text": text, "choices": choices}
    if reacts: e["reacts"] = reacts
    if variants: e["variants"] = variants
    assert key not in EV, key
    EV[key] = e

