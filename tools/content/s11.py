# 강호의 깊이마다 달라지는 외전: 그 강호에서만 찾아오는 일, 같은 줄거리에 붙는 문장, 결말의 한 줄
# 그리고 외전의 길에서 세운 깃발이 결말에 남기는 자취
from dsl import *
H={"difficulty_min":"혈풍"}; G={"difficulty_min":"겁화"}

def deeper(event, hyul, geop):
    assert "deeper" not in STORY[event], event
    STORY[event]["deeper"]={"혈풍":hyul,"겁화":geop}

def deep_event(key, origin, chapters, title, text, choices, depth, reacts=None):
    rnd(key, chapters, title, text, choices, origin=origin, req=dict(depth), reacts=reacts)

# 결말마다 덧붙는 묶음. 조건이 맞는 줄을 정해진 수만큼 쓴다
def rows(origin, many, *items):
    group={"rows":[{"requires":r,"text":t} for r,t in items],"many":many}
    for key,d in ENDINGS.items():
        if d["origin"]==origin: d["frames"].append(group)

# 결말마다 다른 깊은 강호의 한 줄
def depth_line(ending, hyul=None, geop=None):
    group=[]
    if geop: group.append({"requires":dict(G),"text":geop})
    if hyul: group.append({"requires":dict(H),"text":hyul})
    ENDINGS[ending]["frames"].append(group)

