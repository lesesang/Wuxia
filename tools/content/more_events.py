def apply_extra():
    p = os.path.join(ROOT, "events_jianghu.json")
    data = json.load(open(p))
    for key, base, label, text, align, over in EXTRA:
        ev_ = data[key]
        if any(c["label"] == label for c in ev_["choices"]): continue
        src = ev_["choices"][base]
        eff = json.loads(json.dumps(src["outcomes"][0].get("effects", {})))
        eff.pop("alignment", None)
        for k, v in over.items():
            if v is None or v == 0 or v == {}: eff.pop(k, None)
            else: eff[k] = v
        eff["alignment"] = align
        c = {"label": label, "outcomes": [{"text": text, "effects": eff}]}
        if src.get("requires"): c["requires"] = src["requires"]
        ev_["choices"].append(c)
    json.dump(data, open(p, "w"), ensure_ascii=False, indent=2)
    print("extra", len(EXTRA))
if __name__ == "__main__":
    apply_extra()
