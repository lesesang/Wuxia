# 이 소속에 몸담은 무인을 길에서 덮치지 않는다
FACTION = {"수적두목": "수로채", "장강수적": "수로채", "수로채졸": "수로채", "남만술사": "야수궁", "북해고수": "빙궁", "독문고수": "오독문"}

# 세계관에 없던 소속과 그 무공은 지운다
REMOVED_SECTS = ["황보", "해남", "조가", "배화교"]
REMOVED_SKILLS = ["황보신권", "벽력신권", "해남검법", "노도검법", "상산창법", "백룡창법", "화륜곤", "열화곤법", "오뢰장", "역류도법", "남만독침", "호표보", "수왕공"]

def main():
    S = load("sects"); SK = load("skills"); E = load("enemies"); R0 = load("realms")
    for k in REMOVED_SECTS: S.pop(k, None)
    for k, v in SECTS.items(): S[k] = v
    save("sects", S)
    names = {s.get("name") for s in SK.values()} | set(load("market")) | {v.get("name") for v in load("market").values()} | set(load("traits"))
    for k in REMOVED_SKILLS: SK.pop(k, None)
    for k, v in SKILLS.items():
        assert k not in SK or SK[k].get("school") == v["school"], "무공 이름이 겹친다: " + k
        assert SK.get(k) or k not in names, "이름이 겹친다: " + k
        SK[k] = v
    save("skills", SK)
    for k in REMOVED_SECTS: E.pop(k + "장로", None)
    for k, v in elder_enemies(E).items(): E[k] = v
    for k, f in FACTION.items(): E[k]["faction"] = f
    save("enemies", E)
    for i, realm in enumerate(["절정", "초절정", "화경", "현경"]):
        for k in REMOVED_SECTS: R0["breakthrough"][realm]["sect"].pop(k, None)
        for k, lines in REALM_TEXT.items(): R0["breakthrough"][realm]["sect"][k] = lines[i]
    save("realms", R0)
    sect_file = load("events_sect")
    for k in list(sect_file):
        if any(k.startswith(x + "_") or k == "제안_" + x for x in REMOVED_SECTS): del sect_file[k]
    evs = sect_events()
    for k, (label, text, eff) in MADO.items():
        evs[k]["choices"].append(C(label, text, eff, {"dominant": "마도"}, True, "마도"))
    for k, v in evs.items(): sect_file[k] = v
    save("events_sect", sect_file)
    story = load("events_story")
    knock = story["문을_두드리다"]["choices"]
    knock[:] = [c for c in knock if c["outcomes"][0].get("effects", {}).get("sect_offer") not in SECTS and c["outcomes"][0].get("effects", {}).get("sect_offer") not in REMOVED_SECTS]
    alone = knock.pop()  # 혼자 가는 길은 늘 맨 끝에 둔다
    for label, text, sect, req in KNOCK:
        knock.append(C(label, text, {"sect_offer": sect}, req, True, req["dominant"]))
    knock.append(alone)
    save("events_story", story)
    print("소속", len(SECTS), "무공", len(SKILLS), "사건", len(sect_events()))

if __name__ == "__main__":
    main()
